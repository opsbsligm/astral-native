"""Attach official PyPI artifact digests to an actual pip-compile resolution."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
import os
from pathlib import Path
import re
import tempfile
from urllib.parse import quote
from urllib.request import urlopen

from check_dependency_coverage import declared_dependencies, name

# The pinned GitLab parser recognizes pip-compile output by its second line.
LOCK_HEADER = ('#\n# This file is autogenerated by pip-compile with Python 3.12\n'
               '# Artifact digests are attached from official PyPI HTTPS metadata.\n')


def resolved_packages(path):
    packages = {}
    for line in path.read_text().splitlines():
        text = line.strip()
        if not text or text.startswith('#'):
            continue
        pin = re.fullmatch(r'([A-Za-z0-9_.-]+)==([^\s;]+)', text)
        if not pin or name(pin[1]) in packages:
            raise ValueError('Unsupported or duplicate resolved pin')
        packages[name(pin[1])] = pin[2]
    if not packages:
        raise ValueError('Empty dependency resolution')
    for package, version in declared_dependencies().items():
        if packages.get(package) != version:
            raise ValueError('Resolution changes or omits declared package: ' + package)
    return packages


def artifact_hashes(item):
    package, version = item
    url = f'https://pypi.org/pypi/{quote(package, safe="")}/{quote(version, safe="")}/json'
    with urlopen(url, timeout=30) as response:
        raw = response.read(4 * 1024 * 1024 + 1)
    if len(raw) > 4 * 1024 * 1024:
        raise ValueError('PyPI metadata exceeds bound')
    data = json.loads(raw)
    if name(data['info']['name']) != package or data['info']['version'] != version:
        raise ValueError('PyPI metadata identity differs from resolution')
    hashes = {file['digests']['sha256'] for file in data['urls']}
    if not hashes or any(not re.fullmatch(r'[0-9a-f]{64}', digest) for digest in hashes):
        raise ValueError('Missing or malformed PyPI artifact SHA-256')
    return package, version, sorted(hashes)


def generate(resolved, output):
    packages = resolved_packages(resolved)
    # HTTPS PyPI version metadata supplies every published platform artifact hash.
    # Installers verify these hashes when downloading; this does not claim that
    # this maintenance command downloaded or executed every platform artifact.
    with ThreadPoolExecutor(max_workers=4) as executor:
        records = sorted(executor.map(artifact_hashes, packages.items()))
    lines = [LOCK_HEADER]
    for package, version, hashes in records:
        lines.append(f'{package}=={version} \\\n')
        lines.extend('    --hash=sha256:' + digest + (' \\\n' if i + 1 < len(hashes) else '\n')
                     for i, digest in enumerate(hashes))
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', dir=output.parent,
                                         prefix='.pipcompile-', delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(''.join(lines))
        os.replace(temporary, output)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    print(f'{len(records)} resolved packages, {sum(len(h) for _, _, h in records)} artifact hashes')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--resolved', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate(args.resolved, args.output)


if __name__ == '__main__':
    main()
